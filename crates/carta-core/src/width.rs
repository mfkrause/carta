//! East Asian character-width classification.

use std::cmp::Ordering;

/// Whether a Unicode code point occupies two display columns.
#[must_use]
pub fn is_wide(code: u32) -> bool {
    WIDE.binary_search_by(|&(start, end)| {
        if code < start {
            Ordering::Greater
        } else if code > end {
            Ordering::Less
        } else {
            Ordering::Equal
        }
    })
    .is_ok()
}

