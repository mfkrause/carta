//! The glyph each name of the standard emoji module stands for.

/// The glyph `emoji.<name>` stands for, or `None` when the module binds no such name.
pub(super) fn glyph(name: &str) -> Option<&'static str> {
    GLYPHS
        .binary_search_by(|(known, _)| (*known).cmp(name))
        .ok()
        .and_then(|index| GLYPHS.get(index))
        .map(|(_, glyph)| *glyph)
}

