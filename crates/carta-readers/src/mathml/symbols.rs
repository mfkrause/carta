/// The TeX form and reading of `character`, or `None` for a character that stands for itself.
pub(super) fn symbol(character: char) -> Option<(&'static str, Role)> {
    SYMBOLS
        .binary_search_by_key(&character, |(key, _, _)| *key)
        .ok()
        .and_then(|index| SYMBOLS.get(index))
        .map(|(_, tex, role)| (*tex, *role))
}

/// The TeX form and reading of a multi-character operator, or `None` for one with no entry.
pub(super) fn operator(text: &str) -> Option<(&'static str, Role)> {
    OPERATORS
        .binary_search_by_key(&text, |(key, _, _)| *key)
        .ok()
        .and_then(|index| OPERATORS.get(index))
        .map(|(_, tex, role)| (*tex, *role))
}

/// The face command and base character a styled letter of the mathematical alphanumeric plane
/// stands for, or `None` for a character outside those ranges.
pub(super) fn styled_letter(character: char) -> Option<(Option<&'static str>, char)> {
    let position = STYLED_LETTERS.partition_point(|(start, _, _, _)| *start <= character);
    let (_, end, face, offset) = STYLED_LETTERS.get(position.checked_sub(1)?)?;
    if character > *end {
        return None;
    }
    let base = char::from_u32((character as u32).wrapping_sub(*offset))?;
    Some((*face, base))
}

