//! Character and operator tables for the MathML renderer, and the styled-letter ranges of
//! the mathematical alphanumeric plane.

/// How a character reads in math: an ordinary symbol, one spaced from its neighbors, a face-
/// wrapped letter, a space that takes no separator, an infix symbol that spans its row, or a
/// delimiter, either a bracket that stretches with its content or a sign carried inside it.
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum Role {
    /// An ordinary symbol, set as it stands.
    Plain,
    /// A binary or relation symbol, held apart from its operands.
    Spaced,
    /// A letter in a face command, which reads as a group inside an identifier.
    Styled,
    /// A space, which needs no separator before the token after it.
    Tight,
    /// A symbol that spans the row it sits in, delimiting everything around it.
    Infix,
    /// A bracket that opens a delimited group.
    Open,
    /// A bracket that closes a delimited group.
    Close,
    /// A bracket that opens a group at the head of a row and closes one elsewhere.
    Both,
    /// A bracket that divides a delimited group, and closes one at the end of a row.
    Middle,
    /// An opening sign with no TeX delimiter, carried inside an empty bracket.
    OpenSymbol,
    /// A closing sign with no TeX delimiter, carried after an empty bracket.
    CloseSymbol,
    /// A sign that opens at the head of a row and closes elsewhere, as [`Self::Both`] does.
    BothSymbol,
}

impl Role {
    /// Whether the character opens a delimited group when it leads a row.
    pub(super) fn opens(self) -> bool {
        matches!(
            self,
            Self::Open | Self::Both | Self::OpenSymbol | Self::BothSymbol
        )
    }

    /// Whether the character closes a delimited group.
    pub(super) fn closes(self) -> bool {
        matches!(
            self,
            Self::Close | Self::Both | Self::CloseSymbol | Self::BothSymbol
        )
    }

    /// Whether the delimiter is carried inside the group as a sign, leaving the bracket empty.
    pub(super) fn is_sign(self) -> bool {
        matches!(
            self,
            Self::OpenSymbol | Self::CloseSymbol | Self::BothSymbol
        )
    }

    /// Whether the character stands as a delimiter at all.
    pub(super) fn is_delimiter(self) -> bool {
        self.opens() || self.closes() || matches!(self, Self::Middle)
    }
}

