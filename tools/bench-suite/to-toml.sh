#!/usr/bin/env bash
# Converts a `run.sh --json` result file into the committed docs/benchmarks.toml.
# Usage: to-toml.sh <results.json> > docs/benchmarks.toml
set -uo pipefail

[ $# -eq 1 ] || { echo "usage: to-toml.sh <results.json>" >&2; exit 2; }
[ -s "$1" ] || { echo "error: $1 is missing or empty" >&2; exit 1; }

command -v jq >/dev/null 2>&1 || { echo "error: jq not found on PATH" >&2; exit 1; }

# Buffered, so a field rejected halfway through leaves no half-written TOML behind.
toml=$(jq -r '
  # Required fields fail the conversion rather than reaching the TOML as "null" or 0, which would
  # publish a plausible-looking figure nobody measured.
  def q(field): if type == "string" then gsub("\\\\"; "\\\\") | gsub("\""; "\\\"") | "\"" + . + "\""
                else error("missing or non-string \(field)") end;
  def n(field): if type == "number" then tostring else error("missing or non-numeric \(field)") end;

  "# Generated by tools/bench-suite/run.sh --json, converted by tools/bench-suite/to-toml.sh.",
  "# Measurements only: edit by re-running the suite, not by hand.",
  "",
  "[meta]",
  "date = " + (.provenance.date | q("meta.date")),
  "carta = " + (.provenance.carta | q("meta.carta")),
  "pandoc = " + (.provenance.pandoc | q("meta.pandoc")),
  "hyperfine = " + (.provenance.hyperfine | q("meta.hyperfine")),
  "runner = " + (.provenance.runner | q("meta.runner")),
  "warmup = " + (.provenance.warmup | n("meta.warmup")),
  "runs = " + (.provenance.runs | n("meta.runs")),
  "",
  "[binary]",
  "carta = " + (.binary.carta | n("binary.carta (run the `size` surface)")),
  "pandoc = " + (.binary.pandoc | n("binary.pandoc (run the `size` surface)")),
  (
    .timings[]
    | "",
      "[[result]]",
      "surface = " + (.surface | q("result.surface")),
      "group = " + (.group | q("result.group")),
      "bytes = " + (.bytes | n("result.bytes")),
      "runs = " + (.runs | n("result.runs")),
      "carta-ms = " + (.carta_ms | n("result.carta-ms")),
      "carta-sd-ms = " + (.carta_sd_ms | n("result.carta-sd-ms")),
      "pandoc-ms = " + (.pandoc_ms | n("result.pandoc-ms")),
      "pandoc-sd-ms = " + (.pandoc_sd_ms | n("result.pandoc-sd-ms")),
      # Peak RSS is omitted rather than zeroed on hosts where /usr/bin/time cannot report it.
      (if .carta_rss  == null then empty else "carta-rss = "  + (.carta_rss  | tostring) end),
      (if .pandoc_rss == null then empty else "pandoc-rss = " + (.pandoc_rss | tostring) end)
  )
' "$1") || exit 1

printf '%s\n' "$toml"
